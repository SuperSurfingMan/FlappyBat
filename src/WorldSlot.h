#pragma once

// =============================================================================
// 世界渲染槽位(方案二):枚举顺序即绘制顺序。
// MainScene 的槽位管线按此遍历,场景自有内容(贴图组/玩法子系统)与
// IRenderer 派生渲染器在同一张槽位表里排位;每个槽位由"认领它的渲染器"
// 或场景内容填充。雨按 depth 切成 4 档穿插在世界纵深中(远景淡而慢、
// 近景实而快),不再是 MainScene 渲染函数里的手写调用特例。
// =============================================================================
enum class WorldSlot {
    RainFar,        // 雨带0:最底层,垫在背景之下
    Background,     // 背景贴图组
    RainMid,        // 雨带1:背景与前景之间
    Foreground,     // 前景贴图组
    Terrain,        // 地面贴图组
    RainGround,     // 雨带2:地面之上、障碍之下(含贴地水花)
    Obstacles,      // 障碍物(可见时才绘制)
    Items,          // 道具 + 巨化星
    Enemies,        // 怪物世界层(枭王:血月/本体/羽刃/水晶/音爆)
    WindLines,      // 风线(阵风可视化):道具之后、蝙蝠之前,气流贴玩法平面
    Player,         // 蝙蝠
    WeatherScrim,   // 天色变暗遮罩(透明度过低时为空操作)
    RainNear,       // 雨带3:近景,障碍与蝙蝠之前(最实)
    Lightning,      // 闪电本体(动态三角带)+ 全屏闪光(additive)

    Count
};
